"""Stage 3b - Take action, with a human approving every step.

Actions are reversible and logged to data/actions_log.json:
  1. Open a GitHub pull request with the new schema, FAQ and pages
     (needs GITHUB_TOKEN + GITHUB_REPO="owner/repo", e.g. a mirror of the site)
  2. Approve outreach emails -> moved to artifacts/approved_outreach/ ready to send

    python act.py            # interactive approval
    python act.py --dry-run  # show what would happen, change nothing
"""
import argparse
import base64
import datetime as dt
import os
import shutil

import requests

from config import DATA, OUT, read_json, write_json

API = "https://api.github.com"


def log(action, status, detail=""):
    entries = read_json(DATA / "actions_log.json", [])
    entries.append({"ts": dt.datetime.now().isoformat(timespec="seconds"),
                    "action": action, "status": status, "detail": detail})
    write_json(DATA / "actions_log.json", entries)


def approve(prompt, dry):
    if dry:
        print(f"[dry-run] would ask: {prompt}")
        return False
    return input(f"{prompt} [y/N] ").strip().lower() == "y"


def site_files():
    files = [p for p in [OUT / "restaurant_schema.jsonld", OUT / "faq_schema.jsonld",
                         OUT / "faq.html", OUT / "about.md", OUT / "llms.txt"] if p.exists()]
    files += sorted((OUT / "pages").glob("*.html")) if (OUT / "pages").exists() else []
    return files


def open_pr(files):
    tok, repo = os.environ["GITHUB_TOKEN"], os.environ["GITHUB_REPO"]
    h = {"Authorization": f"Bearer {tok}", "Accept": "application/vnd.github+json"}
    base = requests.get(f"{API}/repos/{repo}", headers=h, timeout=30).json()["default_branch"]
    sha = requests.get(f"{API}/repos/{repo}/git/ref/heads/{base}", headers=h, timeout=30).json()["object"]["sha"]
    branch = "aiso-" + dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    requests.post(f"{API}/repos/{repo}/git/refs", headers=h, timeout=30,
                  json={"ref": f"refs/heads/{branch}", "sha": sha}).raise_for_status()
    for f in files:
        rel = f.relative_to(OUT).as_posix()
        requests.put(f"{API}/repos/{repo}/contents/aiso/{rel}", headers=h, timeout=30, json={
            "message": f"AISO: add {rel}", "branch": branch,
            "content": base64.b64encode(f.read_bytes()).decode()}).raise_for_status()
    diag = read_json(DATA / "diagnosis.json", {})
    body = ("Generated by the Café Athena AI-search agent.\n\n**Why:** "
            + diag.get("headline", "") + "\n\n**Files:**\n"
            + "\n".join(f"- `aiso/{f.relative_to(OUT).as_posix()}`" for f in files)
            + "\n\nReview before merging. Close this PR to undo; nothing is live until merged.")
    pr = requests.post(f"{API}/repos/{repo}/pulls", headers=h, timeout=30, json={
        "title": "AI search optimization: schema, FAQ, local pages", "head": branch,
        "base": base, "body": body})
    pr.raise_for_status()
    return pr.json()["html_url"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    dry = ap.parse_args().dry_run

    files = site_files()
    if files:
        print("\nProposed website change (pull request):")
        for f in files:
            print("  +", f.relative_to(OUT))
        if not (os.getenv("GITHUB_TOKEN") and os.getenv("GITHUB_REPO")):
            print("  (set GITHUB_TOKEN and GITHUB_REPO to enable)")
            log("github_pr", "skipped", "no credentials")
        elif approve("Open pull request?", dry):
            try:
                url = open_pr(files)
                print("  Opened:", url)
                log("github_pr", "opened", url)
            except Exception as e:
                print("  Failed:", e)
                log("github_pr", "failed", str(e)[:300])
        else:
            log("github_pr", "declined" if not dry else "dry-run")

    drafts = sorted((OUT / "outreach").glob("*.txt")) if (OUT / "outreach").exists() else []
    approved_dir = OUT / "approved_outreach"
    for d in drafts:
        print("\n" + "-" * 60 + "\n" + d.read_text(encoding="utf-8"))
        if approve(f"Approve this email ({d.name}) for sending?", dry):
            approved_dir.mkdir(exist_ok=True)
            shutil.copy(d, approved_dir / d.name)
            log("outreach_email", "approved", d.name)
        else:
            log("outreach_email", "declined" if not dry else "dry-run", d.name)
    print("\nAll decisions logged to data/actions_log.json")


if __name__ == "__main__":
    main()
